"""
CrewAI multi-agent data scientist
=================================
Converted from the single LangGraph ReAct agent (ds_agent.py) into a crew:

  autopilot:  Interviewer -> EDA Analyst -> Feature Engineer -> ML Engineer -> Reporter
  copilot:    one "fast hands" agent that executes exactly one instruction

Preserved from the original:
  * execute_python with merged stdout/stderr, timeout, auto pip-install + retry
  * notebook logging of successful cells -> exportable .ipynb
  * project memory (survives context loss between agents/tasks)
  * ask_user human-in-the-loop -- now a blocking tool wired to a WebSocket
    session instead of langgraph.interrupt()
"""

