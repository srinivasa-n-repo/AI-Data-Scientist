# Vision model used to actually look at generated figures.
VISION_MODEL = os.environ.get("VISION_MODEL",
                              "bedrock/qwen.qwen3-vl-235b-a22b")


class LookAtPlotTool(BaseTool):
    name: str = "look_at_plot"
    description: str = (
        "LOOK at a .png figure you saved and get a description of what it "
        "actually shows. Use this when the visual shape matters and the "
        "numbers alone are not enough: checking whether a distribution is "
        "bimodal or has a long tail, whether a residual plot shows structure, "
        "whether clusters separate cleanly, or whether a plot came out "
        "unreadable/empty. Do not use it on plots whose content you can "
        "already state precisely from the printed statistics."
    )
    args_schema: Type[BaseModel] = _PlotInput
    session: Session = None

    class Config:
        arbitrary_types_allowed = True

    def _run(self, filename: str, question: str = "") -> str:
        import base64

        if self.session.cancelled:
            return "Cancelled by the user."

        path = os.path.join(self.session.workspace, os.path.basename(filename))
        if not os.path.exists(path):
            return f"No such figure: {filename}. Use list_workspace_files."
        if os.path.getsize(path) > 6_000_000:
            return f"{filename} is too large to inspect."

        self.session.emit("info", f"looking at {os.path.basename(path)} "
                                  f"with {VISION_MODEL.split('/')[-1]}")
        try:
            import litellm

            with open(path, "rb") as f:
                b64 = base64.b64encode(f.read()).decode()

            resp = litellm.completion(
                model=VISION_MODEL,
                messages=[{
                    "role": "user",
                    "content": [
                        {"type": "text",
                         "text": (question or "Describe this chart.") +
                                 " Be concrete and concise (max 120 words). "
                                 "Report what is visible, not what you assume."},
                        {"type": "image_url",
                         "image_url": {"url": f"data:image/png;base64,{b64}"}},
                    ],
                }],
                aws_region_name=os.environ.get("AWS_REGION", "ap-south-1"),
            )
            desc = (resp.choices[0].message.content or "").strip()
            if not desc:
                return f"The vision model returned nothing for {filename}."
            self.session.emit("vision", f"{os.path.basename(path)} :: {desc}")
            return f"Visual inspection of {filename}: {desc}"
        except Exception as e:
            # Vision is an enhancement, never a blocker for the pipeline.
            return (f"Could not inspect {filename} ({type(e).__name__}: {e}). "
                    f"Continue using the printed statistics instead.")


