# ---------------------------------------------------------------------------
# Session-scoped workspaces
# ---------------------------------------------------------------------------
# Every session gets its own directory under workspace/, so uploads, parquet
# checkpoints, plots, report.md, project memory and the notebook log of one
# session can never leak into another.
#
# WORKSPACE_ROOT is overridable via the env so the same code can run both
# locally (./workspace) and inside an AgentCore Runtime microVM, whose only
# reliably writable location is /tmp (set WORKSPACE_ROOT=/tmp/workspace there).
#
# Self-heal a value a Windows/MSYS shell mangled when passing it as a container
# env var: "/tmp/workspace" can arrive as "C:/Users/.../workspace", and on Linux
# os.path.abspath() then yields an unwritable "/app/C:/..." path. On the Linux
# runtime (os.name != "nt") any Windows-style value falls back to /tmp/workspace;
# real Windows runs are left untouched.
_ws_env = os.environ.get("WORKSPACE_ROOT", "workspace")
if os.name != "nt" and ((":" in _ws_env) or ("\\" in _ws_env)):
    _ws_env = "/tmp/workspace"
WORKSPACE_ROOT = os.path.abspath(_ws_env)
os.makedirs(WORKSPACE_ROOT, exist_ok=True)

NOTEBOOK_LOG_NAME = "_notebook_log.jsonl"
PROJECT_MEMORY_NAME = "project_memory.md"

EXEC_TIMEOUT_SECONDS = 600
MAX_RETRY = 5
MAX_OUTPUT_TO_MODEL = 1500

PIP_MAPPING = {
    "cv2": "opencv-python", "PIL": "Pillow", "yaml": "pyyaml",
    "sklearn": "scikit-learn", "bs4": "beautifulsoup4",
    "Crypto": "pycryptodome", "fitz": "PyMuPDF",
    "dateutil": "python-dateutil", "dotenv": "python-dotenv",
}


def new_session_id() -> str:
    return uuid.uuid4().hex[:12]


def session_dir(session_id: str) -> str:
    """Absolute path of a session workspace, created on demand.

    The id is sanitised so a crafted value cannot escape workspace/.
    """
    safe = re.sub(r"[^A-Za-z0-9_-]", "", str(session_id))[:64] or "default"
    path = os.path.join(WORKSPACE_ROOT, safe)
    os.makedirs(path, exist_ok=True)
    return path


def notebook_log_path(ws: str) -> str:
    return os.path.join(ws, NOTEBOOK_LOG_NAME)


def project_memory_path(ws: str) -> str:
    return os.path.join(ws, PROJECT_MEMORY_NAME)


def _log_notebook_cell(ws: str, code: str, output: str) -> None:
    with open(notebook_log_path(ws), "a", encoding="utf-8") as f:
        f.write(json.dumps({"code": code, "output": output[:10000]}) + "\n")


def export_notebook(ws: str, title: str = "Data Science Pipeline") -> str:
    cells = [{
        "cell_type": "markdown", "metadata": {}, "id": "title",
        "source": [f"# {title}\n",
                   f"Generated by Data Scientist AI on {date.today()}.\n",
                   "Run cells top-to-bottom; all paths are relative to this folder.\n"],
    }]
    log = notebook_log_path(ws)
    if os.path.exists(log):
        with open(log, encoding="utf-8") as f:
            for i, line in enumerate(f, start=1):
                entry = json.loads(line)
                cells.append({
                    "cell_type": "code", "execution_count": i, "metadata": {},
                    "id": f"cell-{i}",
                    "source": entry["code"].splitlines(keepends=True),
                    "outputs": [{
                        "output_type": "stream", "name": "stdout",
                        "text": entry["output"].splitlines(keepends=True),
                    }] if entry["output"].strip() else [],
                })
    nb = {
        "cells": cells,
        "metadata": {
            "kernelspec": {"display_name": "Python 3", "language": "python",
                           "name": "python3"},
            "language_info": {"name": "python", "version": "3"},
        },
        "nbformat": 4, "nbformat_minor": 5,
    }
    out_path = os.path.join(ws, "pipeline.ipynb")
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(nb, f, indent=1)
    return out_path


def reset_notebook_log(ws: str) -> None:
    if os.path.exists(notebook_log_path(ws)):
        os.remove(notebook_log_path(ws))


def read_project_memory(ws: str) -> str:
    if os.path.exists(project_memory_path(ws)):
        with open(project_memory_path(ws), encoding="utf-8") as f:
            return f.read()
    return ""


def _truncate_for_model(text: str) -> str:
    if len(text) <= MAX_OUTPUT_TO_MODEL:
        return text
    return "[...output truncated...]\n" + text[-MAX_OUTPUT_TO_MODEL:]


def _detect_missing_package(error_text: str) -> Optional[str]:
    m = re.search(r"No module named ['\"]([^'\"]+)['\"]", error_text)
    if m:
        return m.group(1).split(".")[0]
    m = re.search(r"Missing optional dependency ['\"]([^'\"]+)['\"]", error_text)
    if m:
        return m.group(1)
    m = re.search(r"(\w+) is required for .+ support", error_text)
    if m:
        return m.group(1)
    return None


# ---------------------------------------------------------------------------
# Session: replaces langgraph's stream writer + interrupt().
# Each WebSocket connection owns one Session. Tools emit events into
# `outbox` (forwarded to the browser) and block on `answers` when the
# crew asks the human a question.
# ---------------------------------------------------------------------------
class Session:
    """One chat session: its own workspace directory + event queues."""

    def __init__(self, session_id: str | None = None) -> None:
        self.id = session_id or new_session_id()
        self.workspace = session_dir(self.id)
        self.outbox: "queue.Queue[dict]" = queue.Queue()
        self.answers: "queue.Queue[str]" = queue.Queue()
        self.cancelled = False
        self.seen_answers: set[str] = set()   # answers already sent to the UI

    # convenience paths
    @property
    def notebook_log(self) -> str:
        return notebook_log_path(self.workspace)

    @property
    def project_memory(self) -> str:
        return project_memory_path(self.workspace)

    def emit(self, type_: str, content: str) -> None:
        self.outbox.put({"type": type_, "content": content})

    def ask(self, question: str) -> str:
        self.emit("question", question)
        return self.answers.get()  # blocks the crew thread until the human replies


