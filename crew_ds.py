class _CodeInput(BaseModel):
    code: str = Field(..., description="Python code to execute in the workspace")


class ExecutePythonTool(BaseTool):
    name: str = "execute_python"
    description: str = (
        "Execute Python code inside the persistent `workspace/` directory. "
        "State does NOT persist between calls: save intermediate results to disk "
        "(df.to_parquet('df_stage.parquet')) and reload them next call. "
        "Save every plot with plt.savefig('<name>.png'); never plt.show(). "
        "Print shapes/heads/metrics compactly. Missing packages are auto-installed."
    )
    args_schema: Type[BaseModel] = _CodeInput
    session: Session = None  # injected per-connection

    class Config:
        arbitrary_types_allowed = True

    def _pip_install(self, package: str) -> int:
        base_cmd = [sys.executable, "-m", "pip", "install", package]
        proc = None
        for cmd in (base_cmd, base_cmd + ["--break-system-packages"]):
            proc = subprocess.Popen(cmd, stdout=subprocess.PIPE,
                                    stderr=subprocess.STDOUT, text=True, bufsize=1)
            lines = []
            for line in proc.stdout:
                lines.append(line)
                self.session.emit("pip", line.rstrip())
            proc.wait()
            if proc.returncode == 0:
                return 0
            if "externally-managed-environment" not in "".join(lines):
                return proc.returncode
        return proc.returncode

    def _run(self, code: str) -> str:
        if self.session.cancelled:
            return json.dumps({"success": False, "error": "Cancelled by user."})
        ws = self.session.workspace
        script_path = os.path.join(ws, f"_run_{uuid.uuid4().hex[:8]}.py")
        with open(script_path, "w", encoding="utf-8") as f:
            f.write(code)
        installed = []
        try:
            for attempt in range(MAX_RETRY):
                self.session.emit("info", f"Running Python (attempt {attempt + 1})...")
                process = subprocess.Popen(
                    [sys.executable, "-u", script_path],
                    stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                    text=True, bufsize=1, cwd=ws,
                )
                output_lines = []
                try:
                    for line in process.stdout:
                        output_lines.append(line)
                        self.session.emit("stdout", line.rstrip())
                        if self.session.cancelled:
                            process.kill()
                            return json.dumps({"success": False,
                                               "error": "Cancelled by user."})
                    process.wait(timeout=EXEC_TIMEOUT_SECONDS)
                except subprocess.TimeoutExpired:
                    process.kill()
                    return json.dumps({
                        "success": False,
                        "error": f"Execution timed out after {EXEC_TIMEOUT_SECONDS}s",
                        "output": _truncate_for_model("".join(output_lines)),
                    })

                full_output = "".join(output_lines)
                if process.returncode == 0:
                    _log_notebook_cell(ws, code, full_output)
                    self.session.emit("files_changed", "")
                    return json.dumps({
                        "success": True,
                        "output": _truncate_for_model(full_output),
                        "installed_packages": installed,
                    })

                module = _detect_missing_package(full_output)
                if not module:
                    self.session.emit("error", full_output[-2000:])
                    return json.dumps({
                        "success": False,
                        "output": _truncate_for_model(full_output),
                        "error": "Execution failed (see output for traceback).",
                    })

                pip_package = PIP_MAPPING.get(module, module)
                if pip_package in installed:
                    return json.dumps({
                        "success": False,
                        "error": f"'{pip_package}' installed but import still fails.",
                        "output": _truncate_for_model(full_output),
                    })

                self.session.emit("info", f"Installing missing package: {pip_package}")
                if self._pip_install(pip_package) != 0:
                    return json.dumps({
                        "success": False,
                        "error": f"pip install {pip_package} failed",
                        "output": _truncate_for_model(full_output),
                    })
                installed.append(pip_package)
                self.session.emit("info", f"{pip_package} installed. Retrying...")

            return json.dumps({"success": False,
                               "error": "Maximum retry limit exceeded."})
        finally:
            if os.path.exists(script_path):
                os.remove(script_path)


class _QuestionInput(BaseModel):
    question: str = Field(..., description="One clarifying question for the human")


class AskUserTool(BaseTool):
    name: str = "ask_user"
    description: str = (
        "Pause and ask the human ONE clarifying question. Use it ONLY for "
        "information the human has NOT already provided in their request or "
        "in project memory — re-asking something they already answered is a "
        "serious error. Do not use it at all if the human has said not to ask "
        "questions; choose a sensible default instead. Returns the answer."
    )
    args_schema: Type[BaseModel] = _QuestionInput
    session: Session = None

    class Config:
        arbitrary_types_allowed = True

    def _run(self, question: str) -> str:
        if self.session.cancelled:
            return "Cancelled by the user; stop and summarise what you have."
        answer = self.session.ask(question)
        if self.session.cancelled:
            return "Cancelled by the user; stop and summarise what you have."
        return answer


